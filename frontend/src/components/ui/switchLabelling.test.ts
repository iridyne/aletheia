import { describe, expect, it } from "vitest";
import SETTINGS_SECTION from "./SettingsSection.tsx?raw";
import SWITCH from "./Switch.tsx?raw";

/**
 * A `Switch` inside a labelled `SettingsRow` announced as a bare
 * "checkbox, unchecked" — the visible label was a `<div>` that named nothing, so
 * the control had no accessible name. Chrome's accessibility tree confirmed it
 * empty before the fix and "Prediction observer" after.
 *
 * The fix lives entirely in these two files: the row publishes its label id, the
 * switch adopts it when it has no name of its own. That is what makes it worth
 * asserting here — 65 call sites depend on this pairing holding, and none of
 * them mention it. Delete either half and every unnamed switch silently goes
 * back to being anonymous, with no visual change to notice.
 *
 * This suite runs in `environment: 'node'` with no DOM, so these are structural
 * assertions on source text, not rendered output. They catch the removal of the
 * mechanism; they cannot catch a subtler break in it. The browser measurement
 * above is what verified behaviour.
 */

describe("SettingsRow publishes its label id", () => {
	it("gives the visible label an id generated by useId", () => {
		// A hardcoded id would collide as soon as two rows render.
		expect(SETTINGS_SECTION).toContain("useId");
		expect(SETTINGS_SECTION).toMatch(/const labelId = useId\(\)/);
		expect(SETTINGS_SECTION).toMatch(/id=\{labelId\}[\s\S]{0,120}settings-row-label/);
	});

	it("provides that id to the controls it wraps", () => {
		// Without the Provider the id exists but reaches nothing.
		expect(SETTINGS_SECTION).toContain("SettingsRowLabelContext.Provider");
		expect(SETTINGS_SECTION).toMatch(
			/SettingsRowLabelContext\.Provider value=\{labelId\}/,
		);
	});
});

describe("Switch adopts the row label only when it has no name of its own", () => {
	it("reads the row label from context", () => {
		expect(SWITCH).toContain("useSettingsRowLabelId");
		expect(SWITCH).toMatch(/aria-labelledby=\{ariaLabelledBy\}/);
	});

	it("lets an explicit label, aria-label, or aria-labelledby win", () => {
		// Precedence matters: adopting the row label over a call site's own
		// aria-label would rename controls that were already correct.
		for (const source of ["label", "aria-label", "aria-labelledby"]) {
			expect(SWITCH).toContain(source);
		}
		expect(SWITCH).toMatch(/const named = /);
		expect(SWITCH).toMatch(/named \?[\s\S]{0,80}rowLabelId/);
	});

	it("keeps its wrapper a <label> so a click on the track still toggles", () => {
		// The input is `pointer-events: none` and visually hidden. Label
		// association is the only thing forwarding the click, so swapping the
		// wrapper for a <span> would leave a switch that reads correctly and
		// cannot be operated by mouse.
		expect(SWITCH).toMatch(/<label[\s\S]{0,120}settings-toggle/);
		expect(SWITCH).toContain("settings-switch-input");
	});

	it("requires an explicit persistence mode and renders staged controls distinctly", () => {
		expect(SWITCH).toContain("persistence: SwitchPersistence");
		expect(SWITCH).toContain("data-persistence={persistence}");
		expect(SWITCH).toContain("settings-staged-input");
		expect(SWITCH).toContain("settings-staged-badge");
		expect(SWITCH).toContain("aria-describedby={ariaDescribedBy}");
		expect(SWITCH).toContain("settings-staged-description");
		expect(SWITCH).toContain("!staged &&");
	});

	it("requires SwitchGrid callers to declare the same persistence mode", () => {
		expect(SETTINGS_SECTION).toContain("persistence: SwitchPersistence");
		expect(SETTINGS_SECTION).toContain("persistence={persistence}");
	});
});
