import { useState } from 'react'
import { useQuery } from '@tanstack/react-query'
import { api } from '../api/client'
import StatusPill from '../components/shared/StatusPill'
import { useInspector } from '../context/InspectorContext'
import PnLChart from '../charts/PnLChart'

type Tab = 'pnl' | 'daily' | 'consolidations' | 'post-trade'

export default function Reports() {
  const [tab, setTab] = useState<Tab>('pnl')
  const { setObject } = useInspector()
  const { data: dreaming = [] } = useQuery({ queryKey: ['dreaming'], queryFn: api.getDreamingLogs })
  const { data: reviews = [] } = useQuery({ queryKey: ['reviews'], queryFn: () => api.getKnowledge('daily_review') })
  const { data: postTradeReviews = [] } = useQuery({ queryKey: ['post-trade-reviews'], queryFn: api.getPostTradeReviews })

  return (
    <div>
      <h2 className="page-title">Reports</h2>
      <div className="tab-bar">
        <button className={`tab-btn ${tab === 'pnl' ? 'tab-active' : ''}`} onClick={() => setTab('pnl')}>PnL Chart</button>
        <button className={`tab-btn ${tab === 'daily' ? 'tab-active' : ''}`} onClick={() => setTab('daily')}>Daily Reviews</button>
        <button className={`tab-btn ${tab === 'consolidations' ? 'tab-active' : ''}`} onClick={() => setTab('consolidations')}>Consolidations</button>
        <button className={`tab-btn ${tab === 'post-trade' ? 'tab-active' : ''}`} onClick={() => setTab('post-trade')}>Post-Trade</button>
      </div>

      {tab === 'pnl' && (
        <div className="card">
          <PnLChart />
        </div>
      )}

      {tab === 'daily' && (
        <div className="card">
          {(reviews as any[]).length === 0 ? (
            <p className="hint">No daily reviews yet — generated by the dreaming cycle.</p>
          ) : (
            <table>
              <thead><tr><th>Title</th><th>Status</th><th>Created</th></tr></thead>
              <tbody>
                {(reviews as any[]).map((r: any) => (
                  <tr key={r.id} onClick={() => setObject({ type: 'report', id: r.id, data: r })}>
                    <td>{r.title}</td>
                    <td><StatusPill status={r.status || 'completed'} /></td>
                    <td className="text-faint font-sm">{r.created_at?.slice(0, 16)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </div>
      )}

      {tab === 'consolidations' && (
        <div className="card">
          {(dreaming as any[]).length === 0 ? (
            <p className="hint">No consolidations yet.</p>
          ) : (
            <table>
              <thead><tr><th>Title</th><th>Status</th><th>Created</th></tr></thead>
              <tbody>
                {(dreaming as any[]).slice(0, 15).map((d: any) => (
                  <tr key={d.id} onClick={() => setObject({ type: 'research_note', id: d.id, data: d })}>
                    <td>{d.title}</td>
                    <td><StatusPill status={d.status || 'completed'} /></td>
                    <td className="text-faint font-sm">{d.created_at?.slice(0, 16)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </div>
      )}

      {tab === 'post-trade' && (
        <div className="card">
          {(postTradeReviews as any[]).length === 0 ? (
            <p className="hint">No post-trade reviews yet — generated after paper trade completions.</p>
          ) : (
            <table>
              <thead><tr><th>Title</th><th>Symbol</th><th>Status</th><th>Created</th></tr></thead>
              <tbody>
                {(postTradeReviews as any[]).slice(0, 15).map((r: any) => (
                  <tr key={r.id} onClick={() => setObject({ type: 'report', id: r.id, data: r })}>
                    <td>{r.title}</td>
                    <td>{r.symbol || '—'}</td>
                    <td><StatusPill status={r.status || 'completed'} /></td>
                    <td className="text-faint font-sm">{r.created_at?.slice(0, 16)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </div>
      )}
    </div>
  )
}
