import { useQuery } from '@tanstack/react-query'
import { api } from '../api/client'
import type { StrategyRecord } from '../types'
import PnLChart from '../charts/PnLChart'

export default function Reports() {
  const { data: dreaming = [] } = useQuery({ queryKey: ['dreaming'], queryFn: api.getDreamingLogs })
  const { data: reviews = [] } = useQuery({ queryKey: ['reviews'], queryFn: () => api.getKnowledge('daily_review') })
  const { data: postTradeReviews = [] } = useQuery({ queryKey: ['post-trade-reviews'], queryFn: api.getPostTradeReviews })
  const { data: strategies = [] } = useQuery({ queryKey: ['strategies'], queryFn: api.getStrategies })

  const activeStrategies = (strategies as StrategyRecord[]).filter(
    s => s.state !== 'draft' && s.state !== 'retired'
  )

  return (
    <div>
      <h2 className="page-title">Reports</h2>
      <div className="card">
        <h3>Portfolio PnL</h3>
        <PnLChart />
      </div>
      {activeStrategies.length > 0 && (
        <div className="card">
          <h3>Strategy Metrics</h3>
          {activeStrategies.map(s => <StrategyMetrics key={s.id} strategy={s} />)}
        </div>
      )}
      <div className="card">
        <h3>Daily Reviews</h3>
        {(reviews as any[]).length === 0
          ? <p className="hint">No daily reviews yet — generated by the dreaming cycle.</p>
          : (reviews as any[]).slice(0, 10).map((r: any) => <p key={r.id}>{r.title} — {r.created_at?.slice(0, 16)}</p>)}
      </div>
      <div className="card">
        <h3>Recent Consolidations</h3>
        {(dreaming as any[]).length === 0
          ? <p className="hint">No consolidations yet.</p>
          : (dreaming as any[]).slice(0, 10).map((d: any) => <p key={d.id}>{d.title} — {d.created_at?.slice(0, 16)}</p>)}
      </div>
      <div className="card">
        <h3>Post-Trade Reviews</h3>
        {(postTradeReviews as any[]).length === 0
          ? <p className="hint">No post-trade reviews yet.</p>
          : (postTradeReviews as any[]).slice(0, 10).map((r: any) => <p key={r.id}>{r.title} — {r.created_at?.slice(0, 16)}</p>)}
      </div>
    </div>
  )
}

function StrategyMetrics({ strategy }: { strategy: StrategyRecord }) {
  const { data } = useQuery({
    queryKey: ['strategy-gates', strategy.id],
    queryFn: () => api.getStrategyGates(strategy.id),
    enabled: !!strategy.id,
  })
  const metrics = data?.metrics as Record<string, any> | undefined
  if (!metrics) return null
  return (
    <div style={{ marginBottom: '0.6rem', borderBottom: '1px solid var(--border)', paddingBottom: '0.5rem' }}>
      <p style={{ fontSize: '0.82rem', fontWeight: 600 }}>{strategy.name} <span className="badge badge-blue">{strategy.state}</span></p>
      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(140px, 1fr))', gap: '0.3rem', marginTop: '0.3rem' }}>
        {Object.entries(metrics).filter(([, v]) => v != null && typeof v !== 'string').map(([k, v]) => (
          <div key={k} style={{ fontSize: '0.72rem' }}>
            <span className="text-muted">{k.replace(/_/g, ' ')}</span>
            <br /><span className="mono">{typeof v === 'number' ? (Number.isInteger(v) ? v : v.toFixed(2)) : String(v)}</span>
          </div>
        ))}
      </div>
    </div>
  )
}
